-- FACTORY_RELIABILITY & FACTORY_INTELLIGENCE Tables

CREATE TABLE IF NOT EXISTS FACTORY_RELIABILITY.FAILURE (
    failure_id VARCHAR(64) PRIMARY KEY,
    machine_id VARCHAR(64) NOT NULL REFERENCES FACTORY_CORE.MACHINE(machine_id),
    component_id VARCHAR(64) REFERENCES FACTORY_CORE.COMPONENT(component_id),
    failure_mode VARCHAR(64) NOT NULL,
    occurred_at TIMESTAMP_NTZ NOT NULL,
    root_cause VARCHAR(1024) NOT NULL,
    downtime_hours FLOAT NOT NULL,
    maintenance_action_taken VARCHAR(1024),
    resolved_at TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS FACTORY_RELIABILITY.FAILURE_RISK (
    risk_id VARCHAR(64) PRIMARY KEY,
    machine_id VARCHAR(64) NOT NULL REFERENCES FACTORY_CORE.MACHINE(machine_id),
    failure_mode VARCHAR(64) NOT NULL,
    risk_score FLOAT NOT NULL,
    prediction_horizon_hours INT DEFAULT 72,
    model_version VARCHAR(64) DEFAULT 'v1.2.0-bearing-xgb',
    prediction_timestamp TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    confidence FLOAT DEFAULT 0.85
);

CREATE TABLE IF NOT EXISTS FACTORY_RELIABILITY.HEALTH_ASSESSMENT (
    assessment_id VARCHAR(64) PRIMARY KEY,
    machine_id VARCHAR(64) NOT NULL REFERENCES FACTORY_CORE.MACHINE(machine_id),
    health_status VARCHAR(32) NOT NULL,
    health_score FLOAT NOT NULL,
    primary_concern VARCHAR(256),
    updated_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS FACTORY_INTELLIGENCE.ALERT (
    alert_id VARCHAR(64) PRIMARY KEY,
    machine_id VARCHAR(64) NOT NULL REFERENCES FACTORY_CORE.MACHINE(machine_id),
    component_id VARCHAR(64) REFERENCES FACTORY_CORE.COMPONENT(component_id),
    severity VARCHAR(32) NOT NULL, -- LOW, MEDIUM, HIGH, CRITICAL
    status VARCHAR(32) DEFAULT 'OPEN', -- OPEN, INVESTIGATING, ACTION_PROPOSED, RESOLVED, DISMISSED
    trigger_reason VARCHAR(512) NOT NULL,
    risk_score FLOAT NOT NULL,
    failure_mode VARCHAR(64) DEFAULT 'BEARING_DEGRADATION',
    created_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    acknowledged_at TIMESTAMP_NTZ,
    resolved_at TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS FACTORY_INTELLIGENCE.INVESTIGATION (
    investigation_id VARCHAR(64) PRIMARY KEY,
    alert_id VARCHAR(64) REFERENCES FACTORY_INTELLIGENCE.ALERT(alert_id),
    machine_id VARCHAR(64) NOT NULL REFERENCES FACTORY_CORE.MACHINE(machine_id),
    status VARCHAR(32) DEFAULT 'CREATED', -- CREATED, IN_PROGRESS, WAITING_FOR_APPROVAL, COMPLETED, CLOSED
    failure_mode VARCHAR(64) NOT NULL,
    confidence FLOAT DEFAULT 0.0,
    created_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    completed_at TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS FACTORY_INTELLIGENCE.EVIDENCE (
    evidence_id VARCHAR(64) PRIMARY KEY,
    investigation_id VARCHAR(64) NOT NULL REFERENCES FACTORY_INTELLIGENCE.INVESTIGATION(investigation_id),
    evidence_type VARCHAR(64) NOT NULL, -- TELEMETRY, MAINTENANCE, FAILURE_HISTORY, DOCUMENT, PRODUCTION
    source VARCHAR(128) NOT NULL,
    metric VARCHAR(64) NOT NULL,
    observed_value VARCHAR(256) NOT NULL,
    baseline_value VARCHAR(256),
    relationship VARCHAR(32) DEFAULT 'SUPPORTS', -- SUPPORTS, CONTRADICTS, CORRELATES
    summary VARCHAR(1024) NOT NULL,
    timestamp TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS FACTORY_INTELLIGENCE.FINDING (
    finding_id VARCHAR(64) PRIMARY KEY,
    investigation_id VARCHAR(64) NOT NULL REFERENCES FACTORY_INTELLIGENCE.INVESTIGATION(investigation_id),
    summary VARCHAR(2048) NOT NULL,
    failure_mode VARCHAR(64) NOT NULL,
    confidence FLOAT NOT NULL,
    created_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS FACTORY_INTELLIGENCE.RECOMMENDATION (
    recommendation_id VARCHAR(64) PRIMARY KEY,
    investigation_id VARCHAR(64) NOT NULL REFERENCES FACTORY_INTELLIGENCE.INVESTIGATION(investigation_id),
    title VARCHAR(256) NOT NULL,
    action_description VARCHAR(2048) NOT NULL,
    priority VARCHAR(32) NOT NULL,
    action_required BOOLEAN DEFAULT TRUE,
    estimated_downtime_hours FLOAT DEFAULT 2.0
);
